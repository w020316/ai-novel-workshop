// ============================================================================
// 黄金三章·开篇专项强化
// 依据：网文行业共识——前三章决定留存（签约/推荐/追读都看前三章）。
//       在 chapterNo ≤ 3 时向写作 Prompt 注入开篇专项法则：
//         第 1 章：切入点（危机开场）+ 代入感 + 钩子密度
//         第 2 章：先给再压（兑现首章钩子一部分，同时抛更大期待）
//         第 3 章：第一个小高潮（打脸/翻盘/立誓），完成追读确认
//       并要求借鉴同题材高成绩作品的开头结构（借鉴结构、严禁照抄情节语句）。
// 设计：零依赖、纯函数；chapterNo > 3 返回空串，不影响既有行为。
// ============================================================================

/** 黄金三章判定（前 3 章启用开篇专项强化） */
export const GOLDEN_THREE_CHAPTERS = 3;

/**
 * 生成黄金三章开篇专项 Prompt 块。
 * @param chapterNo - 当前章号（1 起）；> 3 返回空串（无注入）
 */
export function goldenThreePrompt(chapterNo: number): string {
  if (!Number.isFinite(chapterNo) || chapterNo < 1 || chapterNo > GOLDEN_THREE_CHAPTERS) return '';

  const common =
    `【黄金三章·开篇专项法则（本章必须遵守）】\n` +
    `前三章决定读者去留：切入点要快、代入感要强、钩子要密。开篇结构可借鉴同题材高成绩作品\n` +
    `（危机开场/倒叙钩子/金手指亮相等成熟模式），但严禁照抄任何具体情节与语句。\n`;

  if (chapterNo === 1) {
    return (
      common +
      `一、【切入点】正文第一段直接进入冲突现场或危机瞬间：砍掉背景介绍、世界观铺陈、环境描写开场；\n` +
      `    前三段内完成「主角亮相 + 危机压顶 + 悬念抛出」三件事。\n` +
      `二、【代入感】本章内让读者明确知道主角「要什么、怕什么、凭什么」；用感官细节与具体处境\n` +
      `    （被夺、被辱、被逼）引发共鸣，让读者站到主角一边。\n` +
      `三、【钩子密度】每 500 字至少埋一个钩子（新危机/新信息/反转预告）；结尾断在全章最强的悬念上。`
    );
  }

  if (chapterNo === 2) {
    return (
      common +
      `一、【先给再压】立刻兑现第 1 章末钩子的一部分（给出一个爽点或关键信息），让读者尝到甜头；\n` +
      `    紧接着压上更大的危机或代价——甜头只是诱饵，期待感必须升级而非清零。\n` +
      `二、【金手指亮相】本章内让主角的核心优势/外挂完成首次实战亮相，读者必须看到「这本书爽在哪」。\n` +
      `三、【钩子密度】保持开篇的钩子密度，结尾断在新危机爆发的瞬间。`
    );
  }

  return (
    common +
    `一、【第一个小高潮】本章完成追读确认：一场打脸/翻盘/立誓的完整兑现，把前两章的压抑部分清偿，\n` +
    `    让读者在第 3 章末确认「这本书值得追」。\n` +
    `二、【期待升级】高潮兑现的同时抛出下一阶段的更大期待（更强对手/更大赌局/新谜团），\n` +
    `    爽点收尾、悬念开路。\n` +
    `三、【钩子密度】结尾断在下一卷张力拉满的钩子上，严禁平收。`
  );
}

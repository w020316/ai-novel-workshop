// ============================================================================
// 三线并行卷级规划（→ 自适应分卷落地）
// 依据：内置技能「三线并行·剧情跌宕」（啊云云：写小说关键点④）——把三线结构
//       在卷规划层写死成设计文本，随卷摘要流入记忆层与剧情设计/正文生成：
//         主线（50-60%）：故事脊柱，驱动发展，始终向本卷大奖推进
//         支线（30-40%）：枝叶，丰富世界观、塑造配角，可反哺主线但禁止喧宾夺主
//         暗线（10-20%）：暗流，埋真相碎片、制造反转，与「天坑线索」同源递进
//       章内技巧（节奏交错/信息差/伏笔分层）由剧情设计第四原则与技能库注入。
// 设计原则：零依赖、纯函数、确定性可测——与 anticipation.ts 同源同风格。
// ============================================================================

/** 单卷三线设计（主线推进 + 支线安排 + 暗线暗流） */
export interface VolumeThreeLines {
  /** 主线（50-60%）：本卷主线的推进任务（故事脊柱） */
  mainline: string;
  /** 支线（30-40%）：本卷支线的开设/推进/收束安排（枝叶，不喧宾夺主） */
  subplot: string;
  /** 暗线（10-20%）：本卷暗线的埋设/浮现/揭晓动作（暗流，制造反转） */
  hidden: string;
}

/**
 * 按卷序号生成三线并行设计。
 * @param index - 卷下标（0 起）
 * @param count - 总卷数（≥ 4，由 planVolumes 钳制保证）
 */
export function threeLinesDesign(index: number, count: number): VolumeThreeLines {
  const diff = count - index; // 1=末卷 2=倒数第二卷

  // 主线：始终驱动发展，向本卷大奖推进
  let mainline: string;
  if (index === 0) {
    mainline = '确立核心冲突并完成第一引爆点，写清主角「现状—中期目标—最终目标」三层';
  } else if (diff === 1) {
    mainline = '终局对决与清算，主线落定到结局归宿，回应开局的核心冲突';
  } else if (diff === 2) {
    mainline = '真相揭露或巨大危机爆发，主线风险拉满，为终局摊牌蓄力';
  } else {
    mainline = '向本卷大奖层层推进，压抑与释放交替抬升，主线占比保持 50-60%';
  }

  // 支线：塑造配角与世界观，可反哺主线但禁止喧宾夺主
  let subplot: string;
  if (index === 0) {
    subplot = '开设 1 条配角支线（挚友/对手/师长），给配角记忆钩子与私人目标，篇幅不超 40%';
  } else if (diff === 1) {
    subplot = '全部支线在本卷收束，逐一交代重要配角归宿，不留断线';
  } else if (diff === 2) {
    subplot = '支线人物反哺主线（救场/背叛/交出关键证据），让配角弧光与主线共振';
  } else {
    subplot = '支线推进一段（配角自身目标受挫或进展），用节奏交错为主线喘息蓄力';
  }

  // 暗线：暗流埋真相，末卷与主线合流
  let hidden: string;
  if (index === 0) {
    hidden = '埋下暗线第一颗种子（与终极天坑呼应），本卷不揭晓只露端倪';
  } else if (diff === 1) {
    hidden = '暗线全貌揭晓，三线在同一事件合流引爆，回收全部伏笔';
  } else if (diff === 2) {
    hidden = '暗线浮出水面，与主线首次正面交汇，反转前所有碎片重新可读';
  } else {
    hidden = '暗线新增一条碎片线索（暗流占比 10-20%），读者比角色多知道一点';
  }

  return { mainline, subplot, hidden };
}

/** 把三线设计格式化为可拼进卷摘要的结构化文本（记忆层/剧情设计会原样读到） */
export function formatThreeLines(t: VolumeThreeLines): string {
  return `三线安排：主线——${t.mainline}；支线——${t.subplot}；暗线——${t.hidden}。`;
}

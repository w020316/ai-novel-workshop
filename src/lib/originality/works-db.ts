/** 取某平台的全部作品（榜单参考 + 查重） */
export function worksByPlatform(platformId: string): RankedWork[] {
  return WORKS_DB.filter((x) => x.platform === platformId);
}

/** 取某题材的作品 */
export function worksByGenre(genre: string): RankedWork[] {
  return WORKS_DB.filter((x) => x.genre === genre);
}

/** 查某作品详情（title 精确匹配，未命中的作品不在内置库） */
export function findWork(title: string): RankedWork | undefined {
  return WORKS_DB.find((x) => x.title === title.trim());
}

/** 平台 id → 平台对象 */
export function platformOf(id: string): Platform | undefined {
  return PLATFORMS.find((p) => p.id === id);
}

/** 聚合"某平台榜单参考"的纯文本描述（供 LLM prompt / 榜单页展示） */
export function platformRankingHint(platformId: string): string {
  const p = platformOf(platformId);
  if (!p) return '';
  const works = worksByPlatform(platformId).map((x) => x.title).join('、');
  const tagLine = p.tags.slice(0, 6).join('、');
  return [
    `${p.name}（${p.note}）`,
    `高热题材：${tagLine}`,
    works ? `平台代表作参考：${works}（请避免整体复刻这${works.split('、').length}部作品的核心设定）` : '',
  ].filter(Boolean).join('\n');
}

/** 汇总所有平台的代表作清单（榜单参考总览） */
export function allRankingReference(): Platform[] {
  return PLATFORMS.map((p) => ({ ...p }));
}

/**
 * 一款作品的"可复刻体检"关键信息。
 * 用于 checkOriginality：把生成片段/选题与已知作品做相似度比对，命中即提示规避。
 */
export interface RankedWork {
  /** 作品名 */
  title: string;
  /** 所属平台 id */
  platform: string;
  /** 题材/分类 */
  genre: string;
  /** 核心卖点/热梗（一句话） */
  coreTag: string;
  /** 标志性桥段/设定（照搬会显著抬高撞梗风险） */
  tropes: string[];
  /** 标志性人设（主要看是否整体复刻） */
  characters?: string;
}

function w(
  title: string,
  platform: string,
  genre: string,
  coreTag: string,
  tropes: string[],
  characters?: string
): RankedWork {
  return { title, platform, genre, coreTag, tropes, characters };
}

